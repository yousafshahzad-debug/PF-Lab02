#include<stdio.h>
int main()
{
	printf("=========== C ESCAPE SEQUENCES REFERENCE ============\n");
	printf("1.\tTo print a double quote, write:\t\t \\\" \n");
	printf("2.\tTo print a literal backlash, write:\t\\\\ \n");
	printf("3.\tTo insert a newline break, write:\t\\n \n");
	printf("4.\tTo insert a horizontal tab stop, write: \\t \n");
	printf("5.\tTo print a percent sign, write:\t\t %%%% \n");
	printf("=====================================================\n");
	return 0;
}